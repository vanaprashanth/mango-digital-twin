def inject_theme() -> None:
    """Inject the shared CSS once per run and register the Plotly template."""
    st.markdown(_CSS, unsafe_allow_html=True)
    apply_plotly_theme()


def apply_plotly_theme() -> None:
    """Register 'mango_dark' as the default Plotly template (idempotent)."""
    if "mango_dark" not in pio.templates:
        pio.templates["mango_dark"] = go.layout.Template(layout=dict(
            paper_bgcolor="rgba(0,0,0,0)",
            plot_bgcolor=PALETTE["card"],
            font=dict(color=PALETTE["text"]),
            colorway=[PALETTE["green"], PALETTE["gold"], PALETTE["purple"],
                      PALETTE["blue"], PALETTE["red"], "#9BCB6A"],
            xaxis=dict(gridcolor=PALETTE["card_border"], zerolinecolor=PALETTE["card_border"]),
            yaxis=dict(gridcolor=PALETTE["card_border"], zerolinecolor=PALETTE["card_border"]),
            legend=dict(bgcolor="rgba(0,0,0,0)"),
            margin=dict(l=40, r=20, t=50, b=40),
        ))
    pio.templates.default = "mango_dark"


def esc(text) -> str:
    return html.escape("" if text is None else str(text))


def status_pill(state: str, label: str | None = None) -> str:
    """HTML pill: coloured border/text plus an always-visible text label."""
    return f'<span class="mt-pill" style="color:{state_color(state)}">{esc(label or state)}</span>'


def kpi_card(label: str, value: str, note: str = "", state: str | None = None) -> str:
    """HTML for one KPI card. `state` colours the value (Low/Medium/High/...)."""
    colour = f' style="color:{state_color(state)}"' if state else ""
    note_html = f'<div class="mt-kpi-note">{esc(note)}</div>' if note else ""
    return (f'<div class="mt-kpi"><div class="mt-kpi-label">{esc(label)}</div>'
            f'<div class="mt-kpi-value"{colour}>{esc(value)}</div>{note_html}</div>')


def page_header(eyebrow: str, title: str, subtitle: str = "") -> None:
    sub = f'<div class="mt-sub">{esc(subtitle)}</div>' if subtitle else ""
    st.markdown(
        f'<div class="mt-hero"><div class="mt-eyebrow">{esc(eyebrow)}</div>'
        f'<div class="mt-title">{esc(title)}</div>{sub}</div>',
        unsafe_allow_html=True,
    )


def section_header(title: str, caption: str = "") -> None:
    st.subheader(title)
    if caption:
        st.caption(caption)
